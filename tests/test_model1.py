class TestFilterRareVGenes:
    """Tests for filter_rare_v_genes (training V-gene filtering)."""

    def test_basic_filtering(self):
        """Common V genes are kept, rare ones removed."""
        rng = np.random.RandomState(42)
        n = 1000
        # 10 genes with exponentially decaying frequencies
        genes = [f"TRBV{i}" for i in range(1, 11)]
        weights = np.exp(-np.arange(10) * 0.5)
        weights /= weights.sum()
        seqs = pd.DataFrame({
            V_GENE_COL: rng.choice(genes, size=n, p=weights),
        })

        kept = filter_rare_v_genes(seqs, threshold_quantile=0.5)

        assert isinstance(kept, list)
        assert len(kept) > 0
        assert len(kept) < len(genes)  # Some should be filtered
        # Most common gene should always be kept
        most_common = seqs[V_GENE_COL].value_counts().idxmax()
        assert most_common in kept

    def test_all_equal_frequencies(self):
        """When all V genes have equal frequency, all are kept (median = each freq)."""
        seqs = pd.DataFrame({
            V_GENE_COL: ["TRBV1"] * 100 + ["TRBV2"] * 100 + ["TRBV3"] * 100,
        })
        kept = filter_rare_v_genes(seqs, threshold_quantile=0.5)
        assert len(kept) == 3


