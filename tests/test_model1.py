class TestEvaluateOnTest:
    """Tests for evaluate_on_test (per-fold evaluation metrics)."""

    def test_multiclass_metrics(self):
        """Multiclass (4 classes) produces AUROC OvO, AUPRC, confusion matrix."""
        y_true, y_pred, y_proba, classes = _make_synthetic_predictions(
            n_samples=40, n_classes=4,
            class_names=["Covid19", "HIV", "Healthy/Background", "T1D"],
        )
        metrics, raw_preds = evaluate_on_test(
            y_true, y_pred, y_proba, classes,
            fold_id=0, model_name="lasso_cv", n_train=100, n_test=40, n_features=50,
        )

        assert metrics["fold_id"] == 0
        assert metrics["model_name"] == "lasso_cv"
        assert 0.0 <= metrics["accuracy"] <= 1.0
        assert metrics["n_scored"] == 40
        assert metrics["n_abstained"] == 0
        assert metrics["auroc_ovo_weighted"] is not None
        assert metrics["auprc_ovo_weighted"] is not None
        assert metrics["auroc_ovr_per_class"] is not None
        assert len(metrics["auroc_ovr_per_class"]) == 4
        assert metrics["confusion_matrix"] is not None
        assert len(metrics["classes"]) == 4
        assert metrics["mcc"] is not None

        # raw_preds structure
        assert set(raw_preds.keys()) == {"y_true", "y_pred", "y_proba", "classes"}
        assert len(raw_preds["y_true"]) == 40

    def test_binary_metrics(self):
        """Binary (2 classes) produces auroc_binary and auprc_binary."""
        y_true, y_pred, y_proba, classes = _make_synthetic_predictions(
            n_samples=30, n_classes=2,
            class_names=["HIV", "Healthy/Background"],
        )
        metrics, raw_preds = evaluate_on_test(
            y_true, y_pred, y_proba, classes,
            fold_id=1, model_name="lasso_cv", n_train=80, n_test=30, n_features=50,
            reference_class="Healthy/Background",
        )

        assert metrics["auroc_binary"] is not None
        assert 0.0 <= metrics["auroc_binary"] <= 1.0
        assert metrics["auprc_binary"] is not None
        assert 0.0 <= metrics["auprc_binary"] <= 1.0
        # Multiclass metrics should be None for 2 classes
        assert metrics["auroc_ovo_weighted"] is None
        assert metrics["auroc_ovr_per_class"] is None

    def test_binary_no_reference(self):
        """Binary (2 classes) without reference_class skips auroc_binary."""
        y_true, y_pred, y_proba, classes = _make_synthetic_predictions(
            n_samples=30, n_classes=2,
            class_names=["HIV", "Healthy/Background"],
        )
        metrics, _ = evaluate_on_test(
            y_true, y_pred, y_proba, classes,
            fold_id=0, model_name="lasso_cv", n_train=80, n_test=30, n_features=50,
            reference_class=None,
        )
        assert "auroc_binary" not in metrics

    def test_zero_test_specimens(self):
        """Zero test specimens raises ValueError (sklearn rejects empty arrays)."""
        y_true = np.array([], dtype=str)
        y_pred = np.array([], dtype=str)
        y_proba = np.zeros((0, 2))
        classes = np.array(["A", "B"])
        with pytest.raises(ValueError, match="empty"):
            evaluate_on_test(
                y_true, y_pred, y_proba, classes,
                fold_id=0, model_name="lasso_cv", n_train=10, n_test=0, n_features=5,
            )


