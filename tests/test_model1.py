    def test_extract_features_column_alignment(self):
        """Test that extract_features aligns test columns to train columns.

        When test data has V-J pairs not in training (and training has pairs not
        in test), the feature matrix should:
        - Add missing train columns filled with 0
        - Drop test-only columns not in train
        - Result in same column count as training
        """
        model = RepertoireClassifier(gene_locus="TCR", n_pcs=5, verbose=0)
        rng = np.random.RandomState(42)

        # Build synthetic sequences for 2 "specimens"
        def _make_seqs(specimen_ids, v_genes, n_per_specimen=50):
            rows = []
            for sid in specimen_ids:
                for _ in range(n_per_specimen):
                    rows.append({
                        "specimen_label": sid,
                        "participant_label": f"P_{sid}",
                        "v_gene": rng.choice(v_genes),
                        "j_gene": rng.choice(["TRBJ1", "TRBJ2"]),
                        "isotype_supergroup": "TCRB",
                    })
            return pd.DataFrame(rows)

        # Train: specimens S1, S2 with V genes TRBV1-TRBV5
        train_seqs = _make_seqs(["S1", "S2"], [f"TRBV{i}" for i in range(1, 6)])
        X_train = model.extract_features(train_seqs)
        train_vj_cols = model.train_vj_columns_  # not set yet (only set in fit)

        # Manually capture train column structure (extract_features doesn't set
        # train_vj_columns_ — fit() does that). Simulate what fit() does:
        train_vj_columns = {}
        for isotype in model.isotype_groups_:
            cols = X_train.columns[X_train.columns.str.endswith(f":{isotype}")]
            train_vj_columns[isotype] = cols

        # Test: specimens S3, S4 with V genes TRBV3-TRBV7 (overlap: TRBV3-5,
        # new in test: TRBV6-7, missing from test: TRBV1-2)
        test_seqs = _make_seqs(["S3", "S4"], [f"TRBV{i}" for i in range(3, 8)])
        X_test = model.extract_features(
            test_seqs, train_vj_columns=train_vj_columns,
        )

        # Test features should have same columns as train
        assert X_test.shape[1] == X_train.shape[1], (
            f"Column count mismatch: train={X_train.shape[1]}, test={X_test.shape[1]}"
        )
        assert list(X_test.columns) == list(X_train.columns)

        # Test should have 2 specimens
        assert X_test.shape[0] == 2
        assert set(X_test.index) == {"S3", "S4"}


