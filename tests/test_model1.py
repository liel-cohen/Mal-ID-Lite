def _make_synthetic_sequences(
    n_specimens: int = 20,
    n_sequences_per_specimen: int = 100,
    diseases: List[str] = None,
    n_participants_per_disease: int = 5,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Create synthetic sequences and metadata for unit tests.

    Returns (sequences_df, metadata_df) with realistic column structure.
    """
    if diseases is None:
        diseases = ["Covid19", "HIV", "Healthy/Background"]

    rng = np.random.RandomState(42)
    v_genes = [f"TRBV{i}" for i in range(1, 16)]
    j_genes = [f"TRBJ{i}" for i in range(1, 8)]

    all_seqs = []
    all_meta = []
    participant_idx = 0

    for disease in diseases:
        for p in range(n_participants_per_disease):
            participant_label = f"P{participant_idx:04d}"
            specimen_label = f"S{participant_idx:04d}"
            participant_idx += 1

            for _ in range(n_sequences_per_specimen):
                all_seqs.append({
                    "specimen_label": specimen_label,
                    "participant_label": participant_label,
                    "v_gene": rng.choice(v_genes),
                    "j_gene": rng.choice(j_genes),
                    "isotype_supergroup": "TCRB",
                    "cdr3_aa": "CASSLGX",
                })

            all_meta.append({
                "specimen_label": specimen_label,
                "participant_label": participant_label,
                "disease": disease,
                "CV_fold": participant_idx % 3,
            })

    sequences_df = pd.DataFrame(all_seqs)
    metadata_df = pd.DataFrame(all_meta)
    return sequences_df, metadata_df


def _make_synthetic_predictions(
    n_samples: int = 30,
    n_classes: int = 4,
    class_names: List[str] = None,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Create synthetic predictions for evaluate_on_test tests.

    Returns (y_true, y_pred, y_proba, classes).
    """
    rng = np.random.RandomState(42)
    if class_names is None:
        class_names = [f"Class{i}" for i in range(n_classes)]
    classes = np.array(class_names)

    y_true = rng.choice(classes, size=n_samples)
    y_proba = rng.dirichlet(np.ones(n_classes), size=n_samples)
    y_pred = classes[y_proba.argmax(axis=1)]

    return y_true, y_pred, y_proba, classes


def _make_fake_complete_fold(
    output_dir: Path,
    fold_id: int,
    model_name: str,
    model_params: dict = None,
    training_context: str = "cv_single_model",
) -> List[Path]:
    """Create all 4 fold artifacts with realistic sizes for testing."""
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = _get_fold_artifact_paths(output_dir, fold_id, model_name)

    if model_params is None:
        model_params = {"gene_locus": "TCR", "n_pcs": 15, "l1_ratio": 1.0}

    # model.pkl -- needs to be >= _MIN_PKL_BYTES
    model_data = {"weights": np.random.randn(100).tolist(), "padding": "x" * 2000}
    with open(paths[0], "wb") as f:
        pickle.dump(model_data, f)

    # v_genes.json
    with open(paths[1], "w") as f:
        json.dump(["TRBV1", "TRBV2", "TRBV3"], f)

    # results.json
    eval_results = {
        "fold_id": fold_id,
        "model_name": model_name,
        "accuracy": 0.75,
        "mcc": 0.60,
        "auroc_ovo_weighted": 0.90,
        "n_scored": 50,
        "n_abstained": 0,
    }
    with open(paths[2], "w") as f:
        json.dump(eval_results, f)

    # predictions.pkl -- with _meta
    n_samples = 50
    raw_preds = {
        "y_true": np.array(["A", "B"] * (n_samples // 2)),
        "y_pred": np.array(["A", "B"] * (n_samples // 2)),
        "y_proba": np.random.rand(n_samples, 2),
        "classes": np.array(["A", "B"]),
    }
    predictions_rows = [
        {"specimen_label": f"s{i}", "true_disease": "A" if i % 2 == 0 else "B",
         "predicted_disease": "A"}
        for i in range(n_samples)
    ]
    preds_data = {
        "raw_preds": raw_preds,
        "predictions_rows": predictions_rows,
        "_meta": {
            "model_name": model_name,
            "model_params": model_params,
            "training_context": training_context,
            "fold_id": fold_id,
        },
    }
    with open(paths[3], "wb") as f:
        pickle.dump(preds_data, f)

    # Verify pkl sizes are above threshold
    for p in [paths[0], paths[3]]:
        assert p.stat().st_size >= _MIN_PKL_BYTES, (
            f"Test setup bug: {p.name} is {p.stat().st_size} bytes, "
            f"expected >= {_MIN_PKL_BYTES}"
        )

    return paths


def _clean_dir(path: Path) -> Path:
    """Remove and recreate a directory."""
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)
    return path


