class TestFilterToBinaryPair:
    """Tests for filter_to_binary_pair (data filtering for binary mode)."""

    def setup_method(self):
        self.seqs, self.meta = _make_synthetic_sequences(
            n_specimens=20,
            n_sequences_per_specimen=50,
            diseases=["Covid19", "HIV", "Healthy/Background", "T1D"],
            n_participants_per_disease=5,
        )

    def test_filters_to_two_classes(self):
        """Only disease and reference_class remain after filtering."""
        filtered_seqs, filtered_meta = filter_to_binary_pair(
            self.seqs, self.meta, "HIV", "Healthy/Background"
        )
        assert set(filtered_meta[DISEASE_COL].unique()) == {"HIV", "Healthy/Background"}

    def test_excluded_classes_absent(self):
        """Excluded classes have zero rows in both DataFrames."""
        filtered_seqs, filtered_meta = filter_to_binary_pair(
            self.seqs, self.meta, "HIV", "Healthy/Background"
        )
        # Covid19 and T1D participants should not appear
        excluded_participants = set(
            self.meta.loc[
                self.meta[DISEASE_COL].isin({"Covid19", "T1D"}), PARTICIPANT_COL
            ]
        )
        assert not filtered_seqs[PARTICIPANT_COL].isin(excluded_participants).any()
        assert not filtered_meta[PARTICIPANT_COL].isin(excluded_participants).any()

    def test_specimen_consistency(self):
        """Sequences reference only specimens present in filtered metadata."""
        filtered_seqs, filtered_meta = filter_to_binary_pair(
            self.seqs, self.meta, "Covid19", "Healthy/Background"
        )
        meta_specimens = set(filtered_meta[SPECIMEN_COL])
        seq_specimens = set(filtered_seqs[SPECIMEN_COL].unique())
        assert seq_specimens.issubset(meta_specimens)

    def test_row_counts_decrease(self):
        """Filtering to 2 of 4 classes should reduce data."""
        filtered_seqs, filtered_meta = filter_to_binary_pair(
            self.seqs, self.meta, "HIV", "Healthy/Background"
        )
        assert len(filtered_meta) < len(self.meta)
        assert len(filtered_seqs) < len(self.seqs)


