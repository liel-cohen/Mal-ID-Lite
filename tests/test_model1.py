@pytest.mark.integration
class TestModelSaveLoad:
    """Integration test for RepertoireClassifier save/load round-trip."""

    def test_save_load_predictions_match(self, test_loader, integration_output_dir):
        """Saved and loaded model produce identical predictions."""

        from malid_lite.dataloader import PreprocessingStage

        loader = _create_test_loader()

        # Load fold 0 train
        train_data, train_meta = loader.get_fold_data(0, "train", PreprocessingStage.DOWNSAMPLED)
        # Get split participants
        train_participants = set(loader.get_split_participants(0, "cv_single_model", ["train_smaller1", "train_smaller2"]))
        mask = train_data["participant_label"].isin(train_participants)
        train_data = train_data[mask].copy()
        train_meta = train_meta[train_meta["participant_label"].isin(train_participants)].copy()

        # Filter rare V genes
        kept_v_genes = filter_rare_v_genes(train_data)
        train_data = train_data[train_data[V_GENE_COL].isin(kept_v_genes)].copy()

        # Train model
        model = RepertoireClassifier(gene_locus="TCR", n_pcs=10, verbose=0)
        X_train = model.extract_features(sequences=train_data, metadata=train_meta)
        meta_aligned = train_meta.set_index("specimen_label").loc[X_train.index]
        y_train = meta_aligned["disease"]
        groups = meta_aligned["participant_label"]
        model.fit(X_train, y_train, groups=groups)

        # Load test data
        test_data, test_meta = loader.get_fold_data(0, "test", PreprocessingStage.DOWNSAMPLED)
        test_data = test_data[test_data[V_GENE_COL].isin(kept_v_genes)].copy()
        X_test = model.extract_features(test_data, test_meta, train_vj_columns=model.train_vj_columns_)

        # Original predictions
        orig_pred = model.predict(X_test)
        orig_proba = model.predict_proba(X_test)

        # Save and load
        model_path = integration_output_dir / "model_roundtrip.pkl"
        model.save(model_path)
        loaded = RepertoireClassifier.load(model_path)

        # Loaded predictions
        loaded_pred = loaded.predict(X_test)
        loaded_proba = loaded.predict_proba(X_test)

        np.testing.assert_array_equal(orig_pred, loaded_pred)
        np.testing.assert_array_almost_equal(orig_proba, loaded_proba)
        assert loaded.is_fitted_ is True
        np.testing.assert_array_equal(model.classes_, loaded.classes_)


