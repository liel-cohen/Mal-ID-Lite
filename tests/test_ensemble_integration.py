# ---------------------------------------------------------------------------

def test_i05_ensemble_resume(loader, multiclass_base_models, n_jobs):
    """I5: Original run then resume — metrics must match exactly."""
    model_dirs = multiclass_base_models["model_dirs"]
    model_summaries = multiclass_base_models["model_summaries"]

    output_dir = OUTPUT_BASE / "ensemble_resume_test"
    if output_dir.exists():
        shutil.rmtree(output_dir)

    fold_ids = [TEST_FOLD_IDS[0]]
    run_config = {
        "dataset_name": TEST_DATASET_NAME,
        "classification_mode": "multiclass",
        "gene_locus": "TCR",
        "models_included": [1, 2, 3],
        "fold_ids": fold_ids,
    }
    embedding_dir = TEST_DATA_DIR / "embeddings"

    # --- Original run ---
    _, original_summary = train_ensemble(
        loader=loader,
        fold_ids=fold_ids,
        model_nums=[1, 2, 3],
        model_dirs=model_dirs,
        gene_locus="TCR",
        output_dir=output_dir,
        embedding_dir=embedding_dir,
        run_config=run_config,
        model_summaries=model_summaries,
        n_jobs=n_jobs,
        metamodel_cv_n_splits=METAMODEL_CV_N_SPLITS,
    )

    # --- Resume run ---
    _, resume_summary = train_ensemble(
        loader=loader,
        fold_ids=fold_ids,
        model_nums=[1, 2, 3],
        model_dirs={},
        gene_locus="TCR",
        output_dir=output_dir,
        resume=True,
        run_config={**run_config, "resume": True},
        metamodel_cv_n_splits=METAMODEL_CV_N_SPLITS,
    )

    # --- Compare metrics ---
    orig_ens = original_summary["ensemble"]
    resu_ens = resume_summary["ensemble"]
    assert abs(orig_ens["accuracy_global"] - resu_ens["accuracy_global"]) < 1e-10

    for num in [1, 2, 3]:
        orig_bm = original_summary["base_models"][f"model{num}"]
        resu_bm = resume_summary["base_models"][f"model{num}"]
        assert abs(orig_bm["accuracy_global"] - resu_bm["accuracy_global"]) < 1e-10


