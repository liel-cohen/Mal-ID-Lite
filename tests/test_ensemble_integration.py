"""Integration tests for the ensemble (metamodel) pipeline.

Exercises the full ensemble pipeline end-to-end using the test data subset
(72 participants, 4 diseases, 3 folds, 6/disease/fold, ~118K sequences).
Base models are auto-trained from scratch on the first run; subsequent tests
reuse cached artifacts where possible.

Test coverage
-------------
I1.  End-to-end multiclass (TRAIN all models 1+2+3, all folds)
I2.  End-to-end binary (TRAIN all, Covid19 vs Healthy/Background)
I3.  End-to-end multi-binary (TRAIN all, each disease vs reference)
I4.  LOAD after TRAIN (reuse I1 artifacts)
I5.  Ensemble resume (run, then resume from feature matrices)
I6.  Base model RESUME (partial train, then resume)
I7.  Mixed LOAD/TRAIN (LOAD model1+model3 from I1, TRAIN model2 fresh)
I8.  Retrain specific model (force retrain model1 with I1 artifacts)
I9.  Classification mode mismatch (LOAD multiclass artifacts for binary)
I10. Reference class mismatch (LOAD with different reference_class)
I11. Disease list mismatch (LOAD with different diseases)
I12. Cross-model class mismatch (model1 multiclass + model2 binary)
I13. Ensemble resume config mismatch (resume with changed config)
I14. Model subset (--models 1 2, no model 3)
I15. Fill strategy multiclass (fill_0.5, verify fill artifacts and n_abstained=0)
I16. Binary M2 exclusion (verify M2 excluded, no M2 columns, n_abstained=0)

NOTE: Model 2's internal StratifiedGroupKFold uses 5 splits by default, which
can be too many for the small test data. The fixtures pass glmnet_cv_n_splits=2
via training_params to reduce the number of internal CV splits.

Requirements
------------
- Test data at tests/test_data/ (generated by scripts/data/create_test_data.py)
- numpy, pandas, scikit-learn, glmnet, joblib

Expected runtime
----------------
First run (computes embeddings + trains all base models): ~5-15 minutes
Subsequent runs (cached embeddings + artifacts): ~2-5 minutes

Running
-------
From Mal-ID-Lite root:
    python -m pytest tests/test_ensemble_integration.py -v

    # Specific test:
    python -m pytest tests/test_ensemble_integration.py::test_i01_multiclass_end_to_end -v

    # With custom n_jobs:
    python -m pytest tests/test_ensemble_integration.py -v --n-jobs 2
"""

