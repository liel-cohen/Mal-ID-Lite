# I15: Fill strategy (fill_0.5) multiclass
# ---------------------------------------------------------------------------

def test_i15_fill_strategy_multiclass(loader, multiclass_base_models, n_jobs):
    """I15: Multiclass ensemble with fill_0.5 strategy.

    Uses multiclass base models (where M2 has real partial abstentions).
    Verifies fill artifacts, fill_info in results JSON, and that filled
    specimens appear in the feature matrix.
    """
    model_dirs = multiclass_base_models["model_dirs"]
    model_summaries = multiclass_base_models["model_summaries"]

    output_dir = OUTPUT_BASE / "ensemble_fill_multiclass"
    if output_dir.exists():
        shutil.rmtree(output_dir)

    run_config = {
        "dataset_name": TEST_DATASET_NAME,
        "classification_mode": "multiclass",
        "gene_locus": "TCR",
        "models_included": [1, 2, 3],
        "fold_ids": [TEST_FOLD_IDS[0]],
        "model2_abstention_strategy": "fill_0.5",
    }

    embedding_dir = TEST_DATA_DIR / "embeddings"

    fold_results, summary = train_ensemble(
        loader=loader,
        fold_ids=[TEST_FOLD_IDS[0]],
        model_nums=[1, 2, 3],
        model_dirs=model_dirs,
        gene_locus="TCR",
        output_dir=output_dir,
        embedding_dir=embedding_dir,
        disease_filter=None,
        reference_class=None,
        run_config=run_config,
        model_summaries=model_summaries,
        n_jobs=n_jobs,
        metamodel_cv_n_splits=METAMODEL_CV_N_SPLITS,
        model2_abstention_strategy="fill_0.5",
    )

    assert len(fold_results) == 1
    fr = fold_results[0]

    # --- Fill info should be populated (or M2 excluded if fully abstained) ---
    test_fill = fr.get("test_fill_info", {})
    val_fill = fr.get("val_fill_info", {})

    m2_excluded = 2 in test_fill.get("excluded_models", [])
    if m2_excluded:
        # M2 fully abstained — excluded, no fills
        assert test_fill.get("n_filled") is None or test_fill.get("n_filled", 0) == 0
    else:
        # M2 partially abstained — fills should have happened (or no abstentions)
        if test_fill.get("n_filled", 0) > 0:
            assert test_fill["strategy"] == "fill_0.5"
            assert len(test_fill["filled_specimen_labels"]) == test_fill["n_filled"]

    # --- Verify results JSON has fill info ---
    results_json = output_dir / f"fold_{TEST_FOLD_IDS[0]}_ensemble_results.json"
    assert results_json.exists()
    with open(results_json) as f:
        results = json.load(f)
    assert "test_fill_info" in results
    assert "val_fill_info" in results

    # --- Raw feature matrices should be saved ---
    raw_test = output_dir / f"fold_{TEST_FOLD_IDS[0]}_feature_matrix_raw_test.csv"
    raw_val = output_dir / f"fold_{TEST_FOLD_IDS[0]}_feature_matrix_raw_val.csv"
    assert raw_test.exists(), "Raw test feature matrix should be saved"
    assert raw_val.exists(), "Raw validation feature matrix should be saved"

    # --- Verify raw matrix has NaN in M2 columns for filled specimens ---
    if not m2_excluded and test_fill.get("n_filled", 0) > 0:
        raw_df = pd.read_csv(raw_test, index_col="specimen_label")
        m2_cols = [c for c in raw_df.columns
                   if "convergent_cluster_model" in c and c != "true_disease"]
        if m2_cols:
            filled_labels = test_fill["filled_specimen_labels"]
            for spec in filled_labels:
                if spec in raw_df.index:
                    assert raw_df.loc[spec, m2_cols].isna().all(), (
                        f"Raw matrix should have NaN for filled specimen {spec}"
                    )

    # --- Ensemble n_abstained should be 0 (fill keeps all specimens) ---
    ens_metrics = fr["ensemble_metrics"]
    assert ens_metrics["n_abstained"] == 0, (
        f"With fill strategy, ensemble n_abstained should be 0, got {ens_metrics['n_abstained']}"
    )

    # --- Predictions CSV: no specimens should be 'ABSTAINED' ---
    preds_df = pd.read_csv(output_dir / "ensemble_predictions.csv")
    assert (preds_df["ensemble_predicted"] != "ABSTAINED").all(), (
        "With fill strategy, no specimens should be ABSTAINED"
    )

    # --- MD should mention fill strategy ---
    md_files = list(output_dir.glob("RESULTS_*.md"))
    assert len(md_files) == 1
    md_text = md_files[0].read_text()
    assert "fill_0.5" in md_text


