def test_i01_multiclass_end_to_end(loader, multiclass_base_models, n_jobs):
    """I1: End-to-end multiclass ensemble with all 3 base models, all folds."""
    model_dirs = multiclass_base_models["model_dirs"]
    model_summaries = multiclass_base_models["model_summaries"]

    output_dir = OUTPUT_BASE / "ensemble_multiclass"
    if output_dir.exists():
        shutil.rmtree(output_dir)

    run_config = {
        "dataset_name": TEST_DATASET_NAME,
        "classification_mode": "multiclass",
        "gene_locus": "TCR",
        "models_included": [1, 2, 3],
        "fold_ids": TEST_FOLD_IDS,
    }

    embedding_dir = TEST_DATA_DIR / "embeddings"

    fold_results, summary = train_ensemble(
        loader=loader,
        fold_ids=TEST_FOLD_IDS,
        model_nums=[1, 2, 3],
        model_dirs=model_dirs,
        gene_locus="TCR",
        output_dir=output_dir,
        embedding_dir=embedding_dir,
        disease_filter=None,
        reference_class=None,
        run_config=run_config,
        model_summaries=model_summaries,
        n_jobs=n_jobs,
        metamodel_cv_n_splits=METAMODEL_CV_N_SPLITS,
    )

    # --- Verify fold results ---
    assert len(fold_results) == len(TEST_FOLD_IDS)
    for fr in fold_results:
        assert "ensemble_metrics" in fr
        assert "base_model_metrics" in fr
        em = fr["ensemble_metrics"]
        assert 0.0 <= em["accuracy"] <= 1.0
        assert em["mcc"] is not None
        for num in [1, 2, 3]:
            assert num in fr["base_model_metrics"]

    # --- Verify artifacts on disk ---
    assert (output_dir / "run_config.json").exists()
    assert (output_dir / "ensemble_predictions.csv").exists()
    preds_df = pd.read_csv(output_dir / "ensemble_predictions.csv")
    assert len(preds_df) > 0
    assert "specimen_label" in preds_df.columns
    assert "true_disease" in preds_df.columns
    assert "ensemble_predicted" in preds_df.columns

    for fid in TEST_FOLD_IDS:
        assert (output_dir / f"fold_{fid}_ridge_cv_metamodel.joblib").exists()
        assert (output_dir / f"fold_{fid}_metamodel_config.json").exists()
        assert (output_dir / f"fold_{fid}_ensemble_results.json").exists()

    summary_files = list(output_dir.glob("summary_*.json"))
    assert len(summary_files) == 1
    md_files = list(output_dir.glob("RESULTS_*.md"))
    assert len(md_files) == 1

    # --- Verify summary structure ---
    assert "ensemble" in summary
    assert "base_models" in summary
    ens = summary["ensemble"]
    assert "accuracy_global" in ens
    assert ens["accuracy_global"] > 0
    for num in [1, 2, 3]:
        assert f"model{num}" in summary["base_models"]

    # --- Verify RESULTS MD ---
    md_text = md_files[0].read_text()
    assert "Ensemble Training Results" in md_text
    assert "Model Comparison" in md_text


